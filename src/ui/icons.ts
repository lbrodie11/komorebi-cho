const INK = '#f6efe0';
const ACCENT = '#ffa94d';

/** A crisp 9×9 icon canvas; CSS sizes it (18 px by default). Decorative: the button carries the name. */
export function icon(name: IconName): HTMLCanvasElement {
  const rows = ICONS[name];
  const c = document.createElement('canvas');
  c.width = c.height = 9;
  c.className = 'ico';
  c.setAttribute('aria-hidden', 'true');
  const ctx = c.getContext('2d');
  if (ctx)
    rows.forEach((row, y) =>
      [...row].forEach((v, x) => {
        if (v === '.') return;
        ctx.fillStyle = v === 'o' ? ACCENT : INK;
        ctx.fillRect(x, y, 1, 1);
      }),
    );
  return c;
}
